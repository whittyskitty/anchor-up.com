// Populate custom column content
add_action('manage_anchor-up-promotion_posts_custom_column', 'anchor_up_promotion_populate_admin_columns', 10, 2);
function anchor_up_promotion_populate_admin_columns($column, $post_id) {
    switch ($column) {
        case 'promotion_start_date':
            $start_date = get_field('promotion_start_date', $post_id);
            if ($start_date) {
                // Format the date nicely
                $date_timestamp = strtotime($start_date);
                $today = strtotime(date('Ymd'));
                
                echo '<strong>' . esc_html($start_date) . '</strong>';
                
                // Add status indicator
                $end_date = get_field('promotion_end_date', $post_id);
                if ($end_date) {
                    $end_timestamp = strtotime($end_date);
                    if ($today >= $date_timestamp && $today <= $end_timestamp) {
                        echo '<br><span style="color: #10b981; font-size: 11px;">● Active Now</span>';
                    } elseif ($today < $date_timestamp) {
                        $days_until = ceil(($date_timestamp - $today) / 86400);
                        echo '<br><span style="color: #f59e0b; font-size: 11px;">● Starts in ' . $days_until . ' day' . ($days_until != 1 ? 's' : '') . '</span>';
                    } elseif ($today > $end_timestamp) {
                        echo '<br><span style="color: #6b7280; font-size: 11px;">● Ended</span>';
                    }
                }
            } else {
                echo '<span style="color: #9ca3af;">—</span>';
            }
            break;
            
        case 'promotion_end_date':
            $end_date = get_field('promotion_end_date', $post_id);
            if ($end_date) {
                echo esc_html($end_date);
            } else {
                echo '<span style="color: #9ca3af;">—</span>';
            }
            break;
    }
}

