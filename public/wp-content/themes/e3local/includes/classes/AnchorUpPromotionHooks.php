                'promotion_end_date_raw' => $promotion_end_date_raw,
                'has_banner' => !empty($hero_banner),
            );
        }
        
        // Skip if no banner image
        if (empty($hero_banner)) {
            continue;
        }
        
        // Determine start date - prefer marketing_start_date, fallback to promotion_start_date
        $start_date_raw = $marketing_start_date_raw ? $marketing_start_date_raw : $promotion_start_date_raw;
        
        // Skip if we don't have both start and end dates
        if (empty($start_date_raw) || empty($promotion_end_date_raw)) {
            continue;
        }
        
        // Convert dates to timestamps
        // ACF stores dates in Ymd format (e.g., 20251219)
        // Convert to timestamp for comparison
        $start_timestamp = false;
        $end_timestamp = false;
        
        // Parse start date - ACF stores as Ymd (8 digits, e.g., 20251219)
        if (preg_match('/^\d{8}$/', $start_date_raw)) {
            // Format: Ymd (e.g., 20251219) - convert to Y-m-d for strtotime
            $year = substr($start_date_raw, 0, 4);
            $month = substr($start_date_raw, 4, 2);
            $day = substr($start_date_raw, 6, 2);
            $start_timestamp = strtotime($year . '-' . $month . '-' . $day);
