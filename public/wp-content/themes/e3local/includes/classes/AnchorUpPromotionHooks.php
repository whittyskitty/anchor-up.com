// Auto-create registration pages and assign templates
add_action('admin_init', 'anchor_up_promotion_auto_create_registration_pages');
function anchor_up_promotion_auto_create_registration_pages() {
    // Only run once per day to avoid performance issues
    $last_check = get_option('anchor_up_registration_pages_last_check', 0);
    $current_time = time();
    
    // Check once per day
    if (($current_time - $last_check) < 86400) {
        return;
    }
    
    update_option('anchor_up_registration_pages_last_check', $current_time);
    
    // Define pages to create
    $pages_to_create = [
        [
            'title' => 'Anchor Up Promotion Registration',
            'slug' => 'anchor-up-promotion-registration',
            'template' => 'single-anchor-up-promotion-registration.php',
            'template_name' => 'Single Anchor Up Promotion Registration'
        ],
        [
            'title' => 'Anchor Up Website Registration',
            'slug' => 'anchor-up-website-registration',
            'template' => 'single-anchor-up-website-registration.php',
            'template_name' => 'Single Anchor Up Website Registration'
        ]
    ];
    
    foreach ($pages_to_create as $page_data) {
        // Check if page with this template already exists
        $existing_page = get_posts([
            'post_type' => 'page',
            'post_status' => ['publish', 'draft', 'private'],
            'meta_key' => '_wp_page_template',
            'meta_value' => $page_data['template'],
            'posts_per_page' => 1,
            'fields' => 'ids'
        ]);
        
        // If page doesn't exist, create it
        if (empty($existing_page)) {
            // Also check by slug to avoid duplicates
            $page_by_slug = get_page_by_path($page_data['slug']);
            
            if (!$page_by_slug) {
                $page_id = wp_insert_post([
                    'post_title' => $page_data['title'],
                    'post_name' => $page_data['slug'],
                    'post_status' => 'publish',
                    'post_type' => 'page',
                    'post_content' => '',
                    'meta_input' => [
                        '_wp_page_template' => $page_data['template']
                    ]
                ]);
                
                if (!is_wp_error($page_id) && $page_id) {
                    // Ensure template is set correctly
                    update_post_meta($page_id, '_wp_page_template', $page_data['template']);
                }
            } else {
                // Page exists but doesn't have the template - update it
                update_post_meta($page_by_slug->ID, '_wp_page_template', $page_data['template']);
            }
        } else {
            // Page exists with template - make sure it's published
            $page_id = $existing_page[0];
            $page = get_post($page_id);
            if ($page && $page->post_status !== 'publish') {
                wp_update_post([
                    'ID' => $page_id,
                    'post_status' => 'publish'
                ]);
            }
        }
    }
}

