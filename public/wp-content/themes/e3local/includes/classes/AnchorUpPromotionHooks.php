// Handle the sorting
add_action('pre_get_posts', 'anchor_up_promotion_handle_admin_sorting');
function anchor_up_promotion_handle_admin_sorting($query) {
    // Only run in admin and for our post type
    if (!is_admin() || !$query->is_main_query()) {
        return;
    }
    
    if ($query->get('post_type') !== 'anchor-up-promotion') {
        return;
    }
    
    // Get the orderby value
    $orderby = $query->get('orderby');
    
    // Set default sorting to promotion_start_date ASC (most upcoming first)
    if (empty($orderby) || $orderby === 'date') {
        $query->set('meta_key', 'promotion_start_date');
        $query->set('orderby', 'meta_value');
        $query->set('order', 'ASC');
    }
    
    // Handle custom column sorting
    if ($orderby === 'promotion_start_date' || $orderby === 'promotion_end_date') {
        $query->set('meta_key', $orderby);
        $query->set('orderby', 'meta_value');
        
        // Get the order (default to ASC for start date, DESC for end date)
        $order = $query->get('order');
        if (empty($order)) {
            $order = ($orderby === 'promotion_start_date') ? 'ASC' : 'DESC';
            $query->set('order', $order);
        }
    }
}

