// AJAX handler to get sign-up count
add_action('wp_ajax_anchor_up_get_signup_count', 'anchor_up_promotion_ajax_get_signup_count');
function anchor_up_promotion_ajax_get_signup_count() {
    // Verify nonce
    if (!isset($_POST['nonce']) || !wp_verify_nonce($_POST['nonce'], 'anchor_up_signup_count_nonce')) {
        wp_send_json_error(array('message' => 'Invalid nonce'));
        return;
    }
    
    $post_id = isset($_POST['post_id']) ? intval($_POST['post_id']) : 0;
    
    if (!$post_id) {
        wp_send_json_error(array('message' => 'Invalid post ID'));
        return;
    }
    
    $max_kits = get_field('max_numbers_of_kits', $post_id);
    $max_kits = $max_kits ? intval($max_kits) : 0;
    
    // Count sign-ups for this promotion
    $sign_ups_query = new WP_Query(array(
        'post_type' => 'promo-signup',
        'posts_per_page' => -1,
        'meta_query' => array(
            array(
                'key' => 'specific_signup_promotion_relationship',
                'value' => $post_id,
                'compare' => '=',
            ),
        ),
        'fields' => 'ids',
    ));
    
    $sign_ups_count = $sign_ups_query->found_posts;
    
    wp_reset_postdata();
    
    wp_send_json_success(array(
        'max_kits' => $max_kits,
        'sign_ups_count' => $sign_ups_count,
        'remaining' => $max_kits - $sign_ups_count
    ));
}

