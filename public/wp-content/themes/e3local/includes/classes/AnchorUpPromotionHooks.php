// AJAX handler for promo signup form submission
add_action('wp_ajax_submit_promo_signup', 'anchor_up_promotion_ajax_submit_signup');
add_action('wp_ajax_nopriv_submit_promo_signup', 'anchor_up_promotion_ajax_submit_signup');
function anchor_up_promotion_ajax_submit_signup() {
    // Verify ACF form nonce first
    if (!acf_verify_nonce('acf_form')) {
        wp_send_json_error(array('message' => 'Security check failed. Please refresh the page and try again.'));
        return;
    }
    
    // Check if form data exists
    if (empty($_POST['_acf_form'])) {
        wp_send_json_error(array('message' => 'Form data missing.'));
        return;
    }
    
    // Load form configuration - try both methods
    $form = null;
    
    // Try to get form by ID first (if using registered forms)
    if (function_exists('acf_get_form')) {
        $form = acf_get_form($_POST['_acf_form']);
    }
    
    // Fallback to decrypting the form data
    if (!$form) {
        $form = json_decode(acf_decrypt($_POST['_acf_form']), true);
    }
    
    if (empty($form)) {
        wp_send_json_error(array('message' => 'Invalid form data.'));
        return;
    }
    
    // Run kses if needed
    if (isset($form['kses']) && $form['kses'] && isset($_POST['acf'])) {
        $_POST['acf'] = wp_kses_post_deep($_POST['acf']);
    }
    
    // Validate data
    $valid = acf_validate_save_post(true);
    if (!$valid) {
        // Get validation errors
        $errors = acf_get_validation_errors();
        $error_messages = array();
        if (!empty($errors)) {
            foreach ($errors as $error) {
                $error_messages[] = $error['message'];
            }
        }
        wp_send_json_error(array(
            'message' => 'Please correct the errors below.',
            'errors' => $error_messages
        ));
        return;
    }
    
    // Prepare post data
    $post_id = acf_maybe_get($form, 'post_id', 0);
    
    // Add global for backwards compatibility
    $GLOBALS['acf_form'] = $form;
    
    // Allow for custom save
    $post_id = apply_filters('acf/pre_save_post', $post_id, $form);
    
    // Save the post
    acf_save_post($post_id);
    
    // Restore form (potentially modified)
    $form = $GLOBALS['acf_form'];
    
    // Action hook
    do_action('acf/submit_form', $form, $post_id);
    
    // Return success
    wp_send_json_success(array(
        'message' => 'Sign-up submitted successfully!',
        'post_id' => $post_id
    ));
}

