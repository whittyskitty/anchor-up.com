        }
        
        // Parse end date - ACF stores as Ymd (8 digits, e.g., 20251219)
        if (preg_match('/^\d{8}$/', $promotion_end_date_raw)) {
            // Format: Ymd (e.g., 20251219) - convert to Y-m-d for strtotime
            $year = substr($promotion_end_date_raw, 0, 4);
            $month = substr($promotion_end_date_raw, 4, 2);
            $day = substr($promotion_end_date_raw, 6, 2);
            $end_timestamp = strtotime($year . '-' . $month . '-' . $day);
        } else {
            // Try parsing as formatted date string (fallback - from get_field())
            $end_timestamp = strtotime($promotion_end_date_raw);
            if (!$end_timestamp) {
                // Try cleaning up the date string
                $end_date_clean = str_replace(array('/', ','), array('-', ''), $promotion_end_date_raw);
                $end_timestamp = strtotime($end_date_clean);
            }
        }
        
        // Skip if we still can't parse dates
        if (!$start_timestamp || !$end_timestamp) {
            // Log for debugging (only if WP_DEBUG is enabled)
            if (defined('WP_DEBUG') && WP_DEBUG) {
                error_log(sprintf(
                    'Anchor Up Promotion: Could not parse dates for post ID %d. Start (raw): %s, End (raw): %s',
                    $post_id,
                    $start_date_raw,
                    $promotion_end_date_raw
                ));
            }
            if ($debug_mode) {
                $promo_debug['date_parsing_failed'] = true;
                $promo_debug['start_timestamp'] = $start_timestamp;
                $promo_debug['end_timestamp'] = $end_timestamp;
                $debug_info['promotions_checked'][] = $promo_debug;
            }
            continue;
        }
        
        if ($debug_mode) {
            $promo_debug['start_timestamp'] = $start_timestamp;
            $promo_debug['end_timestamp'] = $end_timestamp;
            $promo_debug['start_date_formatted'] = date('Y-m-d', $start_timestamp);
            $promo_debug['end_date_formatted'] = date('Y-m-d', $end_timestamp);
            $promo_debug['check_timestamp'] = $check_timestamp;
            $promo_debug['is_within_range'] = ($check_timestamp >= $start_timestamp && $check_timestamp <= $end_timestamp);
        }
        
        // Check if check_date falls within the date range (inclusive)
        if ($check_timestamp >= $start_timestamp && $check_timestamp <= $end_timestamp) {
            // Handle different ACF image return formats
            $banner_url = '';
            if (is_string($hero_banner)) {
                // Already a URL
                $banner_url = $hero_banner;
            } elseif (is_array($hero_banner)) {
                // Array format - get URL
                $banner_url = isset($hero_banner['url']) ? $hero_banner['url'] : (isset($hero_banner['sizes']['full']) ? $hero_banner['sizes']['full'] : '');
            } elseif (is_numeric($hero_banner)) {
                // Image ID - get URL
                $banner_url = wp_get_attachment_image_url($hero_banner, 'full');
            }
            
            if (!empty($banner_url)) {
                $active_banner = $banner_url;
                $active_start_date = date('Y-m-d', $start_timestamp);
                $active_end_date = date('Y-m-d', $end_timestamp);
                if ($debug_mode) {
                    $promo_debug['matched'] = true;
                    $promo_debug['banner_url'] = $banner_url;
                    $debug_info['promotions_checked'][] = $promo_debug;
                }
                break; // Use first matching promotion
            }
        }
        
        if ($debug_mode && !isset($promo_debug['matched'])) {
            $debug_info['promotions_checked'][] = $promo_debug;
        }
    }
    
    // Return response
    $response_data = array(
        'success' => true,
        'banner_url' => $active_banner,
        'start_date' => $active_start_date,
        'end_date' => $active_end_date,
        'check_date' => $check_date,
    );
    
    if ($debug_mode) {
        $response_data['debug'] = $debug_info;
    }
    
    if ($active_banner) {
        return new WP_REST_Response($response_data, 200);
    } else {
        // Check for default banner on options page
        $default_banner = get_field('default_background_image_lcb', 'option');
        $default_banner_url = '';
        
        if (!empty($default_banner)) {
            // Handle different ACF image return formats
            if (is_string($default_banner)) {
                $default_banner_url = $default_banner;
            } elseif (is_array($default_banner)) {
                $default_banner_url = isset($default_banner['url']) ? $default_banner['url'] : (isset($default_banner['sizes']['full']) ? $default_banner['sizes']['full'] : '');
            } elseif (is_numeric($default_banner)) {
                $default_banner_url = wp_get_attachment_image_url($default_banner, 'full');
            }
        }
        
        // Return success with default banner or null
        $response_data = array(
            'success' => true,
            'banner_url' => $default_banner_url ?: null,
            'start_date' => null,
            'end_date' => null,
            'check_date' => $check_date,
            'message' => $default_banner_url ? 'Using default banner (no active promotion found).' : 'No active promotion banner or default banner found for the specified date.',
        );
        
        if ($debug_mode) {
            $response_data['debug'] = $debug_info;
        }
        
        return new WP_REST_Response($response_data, 200);
    }
}

