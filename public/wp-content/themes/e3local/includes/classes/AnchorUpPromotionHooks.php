// Update post title on ACF save and save Store ID/Name
add_action('acf/save_post', 'anchor_up_promotion_update_post_title_on_save', 20);
function anchor_up_promotion_update_post_title_on_save($post_id) {
    if (isset($_POST['acf'])) {
        $post_type = get_post_type($post_id);
        
        // Handle promo-signup post type
        if ($post_type == "promo-signup") {
            // Get field keys
            $store_name_field = acf_get_field('specific_signup_store_name');
            $account_field = acf_get_field('specific_signup_anchor_customer_number');
            $three_digit_field = acf_get_field('in_store_anchor_up_three_digit_id');
            $promotion_field = acf_get_field('specific_signup_promotion_relationship');
            
            $store_name_key = $store_name_field ? $store_name_field['key'] : 'field_specific_signup_store_name';
            $account_key = $account_field ? $account_field['key'] : 'field_specific_signup_anchor_customer_number';
            $three_digit_key = $three_digit_field ? $three_digit_field['key'] : 'field_in_store_anchor_up_three_digit_id';
            $promotion_key = $promotion_field ? $promotion_field['key'] : 'field_specific_signup_promotion_relationship';
            
            // Get values from POST data first (before ACF saves), then fallback to get_field
            $store_name = '';
            $anchor_customer_number = '';
            $three_digit_id = '';
            $promo_id = null;
            
            if (isset($_POST['acf'][$store_name_key])) {
                $store_name = sanitize_text_field($_POST['acf'][$store_name_key]);
            } else {
                $store_name = get_field('specific_signup_store_name', $post_id);
            }
            
            if (isset($_POST['acf'][$account_key])) {
                $anchor_customer_number = sanitize_text_field($_POST['acf'][$account_key]);
            } else {
                $anchor_customer_number = get_field('specific_signup_anchor_customer_number', $post_id);
            }
            
            if (isset($_POST['acf'][$three_digit_key])) {
                $three_digit_id = sanitize_text_field($_POST['acf'][$three_digit_key]);
            } else {
                $three_digit_id = get_field('in_store_anchor_up_three_digit_id', $post_id);
            }
            
            if (isset($_POST['acf'][$promotion_key])) {
                $promo_id = intval($_POST['acf'][$promotion_key]);
            } else {
                $promotion = get_field('specific_signup_promotion_relationship', $post_id);
                if ($promotion) {
                    if (is_array($promotion)) {
                        $promo_id = is_numeric($promotion[0]) ? intval($promotion[0]) : (is_object($promotion[0]) ? $promotion[0]->ID : null);
                    } elseif (is_object($promotion)) {
                        $promo_id = $promotion->ID;
                    } elseif (is_numeric($promotion)) {
                        $promo_id = intval($promotion);
                    }
                }
            }
            
            // Get promotion name
            $promo_name = '';
            if ($promo_id) {
                $promo_name = get_the_title($promo_id);
            }
            
            // Build post title in format: Store Name - Account Number - 3 Digit Code - Promo Name
            $title_parts = array();
            
            if (!empty($store_name)) {
                $title_parts[] = $store_name;
            }
            
            if (!empty($anchor_customer_number)) {
                $title_parts[] = $anchor_customer_number;
            }
            
            if (!empty($three_digit_id)) {
                $title_parts[] = $three_digit_id;
            }
            
            if (!empty($promo_name)) {
                $title_parts[] = $promo_name;
            }
            
            // Only update if we have at least one part
            if (!empty($title_parts)) {
                $post_title = implode(' - ', $title_parts);
                
                // Update the post title
                $post_data = array(
                    'ID' => $post_id,
                    'post_title' => $post_title,
                );
                
                // Remove this hook temporarily to avoid infinite loop
                remove_action('acf/save_post', 'anchor_up_promotion_update_post_title_on_save', 20);
                wp_update_post($post_data);
                add_action('acf/save_post', 'anchor_up_promotion_update_post_title_on_save', 20);
            }
        }
        
        if ($post_type == "promo-submission") {
            $store_id = '';
            $store_name = '';
            
            // Get Store ID and Name from form or store object
            // ACF uses field keys in $_POST['acf']
            if (isset($_POST['acf']['field_store_id_promo'])) {
                $store_id = sanitize_text_field($_POST['acf']['field_store_id_promo']);
            }
            if (isset($_POST['acf']['field_store_name_promo'])) {
                $store_name = sanitize_text_field($_POST['acf']['field_store_name_promo']);
            }
            
            // If not in form, try to get from store object
            if (empty($store_id) || empty($store_name)) {
                if (class_exists('\STW\AnchorUp\AnchorUp')) {
                    $store = \STW\AnchorUp\AnchorUp::isAnchorUpAdmin(true);
                    if ($store) {
                        if (empty($store_id) && isset($store->autonumber)) {
                            $store_id = $store->autonumber;
                        }
                        if (empty($store_name) && isset($store->name)) {
                            $store_name = $store->name;
                        }
                    }
                } elseif (function_exists('Store')) {
                    $store = Store();
                    if ($store) {
                        if (empty($store_id)) {
                            $store_id = method_exists($store, 'autonumber') ? $store->autonumber : (isset($store->autonumber) ? $store->autonumber : '');
                        }
                        if (empty($store_name)) {
                            $store_name = method_exists($store, 'name') ? $store->name : (isset($store->name) ? $store->name : '');
                        }
                    }
                }
            }
            
            // Save Store ID and Store Name to post meta
            if (!empty($store_id)) {
                update_post_meta($post_id, 'store_id', $store_id);
                // Also update ACF field if it exists
                update_field('store_id', $store_id, $post_id);
            }
            if (!empty($store_name)) {
                update_post_meta($post_id, 'store_name', $store_name);
                // Also update ACF field if it exists
                update_field('store_name', $store_name, $post_id);
            }
            
            // Update post title
            if (class_exists('\STW\AnchorUp\AnchorUp')) {
                $store = \STW\AnchorUp\AnchorUp::isAnchorUpAdmin(true);

                $promo_id = isset($_POST['acf']['field_64381a6072103']) ? $_POST['acf']['field_64381a6072103'] : null;

                if ($promo_id) {
                    $promo_post = get_post($promo_id);
                    if ($promo_post) {
                        $promo_post_title = $promo_post->post_title;
                        $post_title = ($store_name ?: ($store ? $store->name : '')) . ' - Acct #: ' . ($store ? $store->anchor_customer_id : '') . ' - Store Id: ' . ($store_id ?: ($store ? $store->autonumber : '')) . ' - Promo: ' . $promo_post_title;

                        $post_data = array(
                            'ID' => $post_id,
                            'post_title' => $post_title,
                        );

                        wp_update_post($post_data);
                    }
                }
            }
        }
    }
}

// Custom validation rule to check for overlapping date ranges
add_filter('acf/validate_value/name=promotion_start_date', 'anchor_up_promotion_validate_start_date', 10, 4);
function anchor_up_promotion_validate_start_date($valid, $value, $field, $input) {
    $post_id = isset($_POST['post_ID']) ? $_POST['post_ID'] : 0;
    $meta_key_start = 'promotion_start_date';
    $meta_key_end = 'promotion_end_date';

    $start_date = strtotime(get_field($meta_key_start, $post_id));
    $end_date = strtotime(get_field($meta_key_end, $post_id));

    if ($start_date && $end_date && $start_date >= $end_date) {
        $valid = 'Start date must be before end date.';
    }

    // Check for overlapping date ranges
    $query = new WP_Query(array(
        'post_type' => 'anchor-up-promotion',
        'post__not_in' => array($post_id),
        'meta_query' => array(
            'relation' => 'AND',
            array(
                'key' => $meta_key_start,
                'value' => $value,
                'compare' => '<=',
                'type' => 'DATE',
            ),
            array(
                'key' => $meta_key_end,
                'value' => $value,
                'compare' => '>=',
                'type' => 'DATE',
            ),
        ),
    ));

    if ($query->have_posts()) {
        $overlapping_posts = array();
        while ($query->have_posts()) {
            $query->the_post();
            $post_title = get_the_title();
            $post_id_overlap = get_the_ID();
            $edit_link = get_edit_post_link($post_id_overlap);
            $overlapping_posts[] = "<a href='$edit_link' target='_blank'>$post_title</a>";
        }
        wp_reset_query();

        $overlapping_posts_html = implode(', ', $overlapping_posts);
        $valid = "Date range overlaps with the following existing entries: $overlapping_posts_html";
    }

    return $valid;
}

