        'posts_per_page' => -1,
        'orderby' => 'meta_value',
        'meta_key' => 'marketing_to_anchor_up_stores_start_date',
        'order' => 'DESC',
        'meta_query' => array(
            'relation' => 'OR',
            array(
                'key' => 'marketing_to_anchor_up_stores_start_date',
                'compare' => 'EXISTS',
            ),
            array(
                'key' => 'promotion_start_date',
                'compare' => 'EXISTS',
