        $debug_info['check_timestamp'] = $check_timestamp;
        $debug_info['promotions_checked'] = array();
    }
    
    // Loop through promotions to find one with active date range
    foreach ($promotions as $promotion) {
        $post_id = $promotion->ID;
        
        // Get date fields - try raw meta first (stored as Ymd format), fallback to get_field()
        // ACF stores dates in Ymd format in the database, but get_field() returns formatted dates
        $marketing_start_date_raw = get_post_meta($post_id, 'marketing_to_anchor_up_stores_start_date', true);
        $promotion_start_date_raw = get_post_meta($post_id, 'promotion_start_date', true);
        $promotion_end_date_raw = get_post_meta($post_id, 'promotion_end_date', true);
        
        // If raw meta is empty, try get_field() as fallback (might be formatted)
        if (empty($marketing_start_date_raw)) {
            $marketing_start_date_raw = get_field('marketing_to_anchor_up_stores_start_date', $post_id);
